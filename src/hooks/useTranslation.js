export function getCurrentLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved) return saved;
  return detectLanguageFromBrowser();
}

export function useTranslation() {
  const [lang, setLangState] = useState(getCurrentLang);

  useEffect(() => {
    const handler = () => setLangState(getCurrentLang());
    window.addEventListener("lang_change", handler);
    return () => window.removeEventListener("lang_change", handler);
  }, []);

  // On first mount, attempt IP geolocation to set language if none saved
  useEffect(() => {
    if (localStorage.getItem(LANG_KEY)) return;
    detectLanguageFromIP().then(code => {
      if (code && !localStorage.getItem(LANG_KEY)) {
        localStorage.setItem(LANG_KEY, code);
        window.dispatchEvent(new Event("lang_change"));
      }
    });
  }, []);

  const setLang = (code) => {
    localStorage.setItem(LANG_KEY, code);
    window.dispatchEvent(new Event("lang_change"));
  };

  const t = (key) => TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS["en"]?.[key] ?? key;

  return { t, lang, setLang, languages: LANGUAGES };
}